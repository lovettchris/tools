
import argparse
from typing import Tuple

def parse_args():
    """ parse the --tax bill and --stock_price arguments """

    parser = argparse.ArgumentParser(description="Estimate how many shares to sell to pay a tax bill")
    parser.add_argument("--tax", type=float, required=True, help="Original tax bill in dollars")
    parser.add_argument("--stock_price", type=float, required=True, help="Price per share of the stock in dollars")
    parser.add_argument("--tax_rate", type=float, default=0.20, help="Tax rate applied to the stock sale (decimal), default 0.15")
    return parser.parse_args()


def compute_total_stock_sales(tax: float, stock_price: float, tax_rate: float = 0.15) -> Tuple[float, float]:
    """This function computes how many shares need to be sold to raise cash to
    pay an original tax bill. Selling stock creates additional taxable events
    (tax on the sale itself), which in turn require selling more stock. The
    function iterates until the additional sale is negligible and returns a
    tuple of (total_shares_sold, total_tax_paid).

    Parameters
    - tax: original tax bill in dollars
    - stock_price: price per share in dollars
    - tax_rate: fraction of sale proceeds paid as tax (e.g., 0.15)
    """

    if stock_price <= 0:
        raise ValueError("stock_price must be > 0")
    if tax < 0:
        raise ValueError("tax must be >= 0")
    if not (0 <= tax_rate < 1):
        raise ValueError("tax_rate must be in [0, 1)")

    # If tax is zero, nothing to sell
    if tax == 0:
        return 0.0, 0.0

    # Iteratively compute required sales until convergence
    total_shares = 0.0
    total_tax_paid = tax
    remaining_tax_to_cover = tax
    eps = 1
    max_iter = 1000
    it = 0
    while remaining_tax_to_cover > eps and it < max_iter:
        shares_needed = remaining_tax_to_cover / stock_price
        total_shares += shares_needed

        # The sale itself generates tax equal to tax_rate * gross_needed
        sale_tax = tax_rate * remaining_tax_to_cover
        total_tax_paid += sale_tax

        # Now we need to cover the tax generated by this sale in the next iteration
        remaining_tax_to_cover = sale_tax
        it += 1

    # Return closed-form values (they are mathematically exact)
    return total_shares, total_tax_paid


def main():
    args = parse_args()
    total_sale, total_tax = compute_total_stock_sales(args.tax, args.stock_price, args.tax_rate)
    print(f"Total sale = {total_sale} shares")
    print(f"Total tax = $ {total_tax} ")


if __name__ == "__main__":
    main()